// Lets the native app talk plain HTTP to a Starlink dish on its own Wi-Fi (192.168.100.1),
// and nothing else. Used by the Starlink page's "Connect to my dish".
//
// iOS: local network permission text plus an App Transport Security exception.
// Android: a network security config that allows cleartext only to the dish. A debug-only
// copy also allows cleartext everywhere so the Metro dev server keeps working.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, withInfoPlist } = require('expo/config-plugins');

const DISH_HOST = '192.168.100.1';
const RES_NAME = 'network_security_config';

const releaseXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-starlink-local-network.js -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">${DISH_HOST}</domain>
  </domain-config>
</network-security-config>
`;

const debugXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-starlink-local-network.js (debug builds only: Metro needs cleartext) -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true" />
</network-security-config>
`;

function withIos(config, { localNetworkText }) {
  return withInfoPlist(config, (c) => {
    c.modResults.NSLocalNetworkUsageDescription = localNetworkText;
    const ats = c.modResults.NSAppTransportSecurity ?? {};
    ats.NSAllowsLocalNetworking = true;
    ats.NSExceptionDomains = {
      ...(ats.NSExceptionDomains ?? {}),
      [DISH_HOST]: { NSExceptionAllowsInsecureHTTPLoads: true, NSIncludesSubdomains: false },
    };
    c.modResults.NSAppTransportSecurity = ats;
    return c;
  });
}

function withAndroid(config) {
  config = withDangerousMod(config, [
    'android',
    async (c) => {
      const src = path.join(c.modRequest.platformProjectRoot, 'app', 'src');
      for (const [variant, xml] of [['main', releaseXml], ['debug', debugXml]]) {
        const dir = path.join(src, variant, 'res', 'xml');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, `${RES_NAME}.xml`), xml);
      }
      return c;
    },
  ]);
  return withAndroidManifest(config, (c) => {
    const app = c.modResults.manifest.application?.[0];
    if (app) app.$['android:networkSecurityConfig'] = `@xml/${RES_NAME}`;
    return c;
  });
}

module.exports = function withStarlinkLocalNetwork(config, props = {}) {
  const localNetworkText =
    props.localNetworkText ??
    'OnMyLead connects to your Starlink dish on its Wi-Fi to show its status. Nothing else on your network is touched.';
  return withAndroid(withIos(config, { localNetworkText }));
};
